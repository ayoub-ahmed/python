# 3-3. Your Own List
# Store different modes of transportation in a list and
# print a statement about each one.

transportation = [
    "Honda motorcycle",
    "Toyota Land Cruiser",
    "Tesla Model 3",
]

print(f"I would like to own a {transportation[0]}.")
print(f"I would like to own a {transportation[1]}.")

# Negative indices access items from the end of the list.

print(f"I would like to own a {transportation[-1]}.")