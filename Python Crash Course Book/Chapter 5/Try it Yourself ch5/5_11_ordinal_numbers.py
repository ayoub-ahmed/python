# 5_11_ordinal_numbers.py

ranking = list(range(1, 10))

for rank in ranking:
    if rank == 1:
        print("1st")
    elif rank == 2:
        print("2nd")
    elif rank == 3:
        print("3rd")
    elif rank == 4:
        print("4th")
    elif rank == 5:
        print("5th")
    elif rank == 6:
        print("6th")
    elif rank == 7:
        print("7th")
    elif rank == 8:
        print("8th")
    else:
        print("9th")